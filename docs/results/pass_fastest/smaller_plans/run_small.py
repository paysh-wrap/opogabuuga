"""Pro 150K "fast pass" structure (brake150 U1) scaled to Lucid Pro 25K / 50K / 100K EVALUATION (research only; backend/app, config/, frontend/ untouched).
Simulator: ../sim150.py with the brake150 in-memory size bands (brake150.load_sim), plan constants swapped per plan (same values as the old loader
pass_faster_100/run_100.py P[k]; check() re-asserts them and reproduces BASE). Everything else unchanged: EOD MLL + lock, DLL + LucidScale,
consistency + day stop, kill distance + room check, D57 shrink, plan per-trade cap, one position at a time, flat by close.
Grid per plan: NOISE micros {s-1, s, s+1} (min 1, s = round(4 x MLL/4500)), NOISE stop/micro {100,150,250} (25K + 50K also $50, $75: user addition; $50 stream generated by gen_lib on first use), CANDACE fixed micros {0..3},
brake at cushion < MLL/3 to {half = ceil(n/2), 1 micro} for NOISE and CANDACE together (none if both already 1).  C40 (day stop 38 %) and C50 (48 %).
Run: cd <worktree>/backend && PYTHONPATH=. /usr/local/bin/python3 ../docs/results/pass_fastest/smaller_plans/run_small.py [check]
"""
import sys, os, json, time
import multiprocessing as mp
HERE = os.path.dirname(os.path.abspath(__file__)); PF = os.path.dirname(HERE)
sys.path.insert(0, PF); sys.path.insert(0, PF + "/brake150")
import brake150 as B

PLANS = {   # size, target, mll, lock_trig, lock_lvl, dll, cap_trade  (kill 50, margin 40, mpd 1, cost 2, LucidScale on: identical on every plan)
    25: (25000., 1250., 1000., 26100., 25100., 600., 500.),
    50: (50000., 3000., 2000., 52100., 50100., 1200., 1000.),
    100: (100000., 6000., 3000., 103100., 100100., 1800., 1500.),
}
BASE = {25: dict(stop=250, N=1, brake=None), 50: dict(stop=250, N=2, brake=(0.5, 1)), 100: dict(stop=250, N=2, brake=(0.3, 1))}   # shipped size rows
CONS = B.CONS
T = 1.0 / 3.0
_S = {}


def sim(k, cn):
    if (k, cn) not in _S:
        S = B.load_sim()
        S.SIZE, S.TARGET, S.MLL, S.LOCK_TRIG, S.LOCK_LVL, S.DLL0, S.CAP_TRADE = PLANS[k]
        S.CONS, ds = CONS[cn]; S.DSTOP = ds * S.TARGET
        _S[(k, cn)] = S
    return _S[(k, cn)]


def grid(k):
    s = max(1, round(4 * PLANS[k][2] / 4500))
    out = {}
    for N in sorted({max(1, s - 1), s, s + 1}):
        for stop in ((50, 75, 100, 150, 250) if k in (25, 50) else (100, 150, 250)):
            for nc in (0, 1, 2, 3):
                br = set()
                for hn, hc in ((-(-N // 2), -(-nc // 2)), (1, min(nc, 1))):
                    if hn < N or hc < nc: br.add((hn, hc))
                for b in (sorted(br) or [None]):
                    cfg = dict(stop=stop, N=N, nc=nc, brake=None, cbands=())
                    if b:
                        if b[0] < N: cfg["brake"] = (T, b[0])
                        if b[1] < nc: cfg["cbands"] = ((T, b[1]),)
                    out[f"N{N}@{stop}+C{nc}" + (f" brake->{b[0]}/{b[1]}" if b else " nobrake")] = cfg
    return out


def ev(job):
    k, name, cn, cfg = job
    S = sim(k, cn); e = S.evaluate(S.mk(**cfg))
    r = {w: {x: e[w][x] for x in ("pass", "stuck", "run", "p60", "med")} for w in ("ALL", "PICK", "JUDGE")}
    r["chain"] = {x: e["ch"][x] for x in ("mean", "med", "cens")}
    r["profit"] = e["static"]["profit"]; r["dd"] = e["static"]["dd"]; r["tpw"] = e["static"]["tpw"]
    r["cfg"] = {a: (list(v) if isinstance(v, tuple) else v) for a, v in cfg.items()}
    return f"{k}|{cn}|{name}", r


def check():
    sys.path.insert(0, PF + "/../pass_faster_100")
    import run_100 as R
    for k in PLANS:
        p = R.P[k]
        assert (p["size"], p["target"], p["mll"], p["lock_trig"], p["lock_lvl"], p["dll"], p["cap_trade"]) == PLANS[k]
        assert (p["kill"], p["margin"], p["mpd"], p["cost"], p["scale"], p["cons"], p["day_stop"]) == (50, 40, 1, 2.0, True, 40, 0.38 * p["target"])
    print("plan constants = old loader")
    ref = json.load(open(PF + "/../pass_faster_100/results.json")); ok = True
    for k in PLANS:
        _, r = ev((k, "BASE", "C40", BASE[k]))
        for w in ("ALL", "PICK", "JUDGE"):
            o = ref[f"BASE|{k}|roll|{w}"]; n = r[w]
            d = max(abs(o["pass_"] - n["pass"]), abs(o["stuck"] - n["stuck"]), abs(o["p60"] - n["p60"]), abs((o["med"] or 0) - (n["med"] or 0)))
            ok &= d < 0.5
            print(k, w, f"pass {n['pass']:.1f}/{o['pass_']:.1f} stuck {n['stuck']:.1f}/{o['stuck']:.1f} <=60d {n['p60']:.1f}/{o['p60']:.1f} med {n['med']}/{o['med']}", "OK" if d < 0.5 else "DIFF")
        ok &= abs(r["profit"] - ref[f"BASE|{k}|static|ALL"]["tp"]) < 1e-6
        print(k, "profit", r["profit"], "old", ref[f"BASE|{k}|static|ALL"]["tp"])
    print("BASE REPRODUCED" if ok else "BASE MISMATCH"); return ok


if __name__ == "__main__":
    if not check(): sys.exit(1)
    if len(sys.argv) > 1 and sys.argv[1] == "check": sys.exit()
    t0 = time.time()
    jobs = []
    for k in PLANS:
        for cn in CONS:
            jobs.append((k, "BASE", cn, BASE[k]))
            jobs += [(k, n, cn, c) for n, c in grid(k).items()]
    print(len(jobs), "jobs", flush=True)
    with mp.Pool(4) as p: res = dict(p.imap_unordered(ev, jobs, chunksize=4))
    res = {k: res[k] for k in sorted(res)}
    json.dump(res, open(HERE + "/results.json", "w"), indent=1, default=float)
    print("done", round(time.time() - t0), "s")
