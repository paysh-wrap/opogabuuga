"""Generate config/rules/lucid_{pro,flex}_{25k..150k}.yaml from the LucidDaily 25K template + Lucid's help center
(fetched 2026-11-05; article IDs in comments). Unstated values carry # VERIFY. Re-run after editing the tables."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "config" / "rules"
TPL = (ROOT / "lucid_daily_25k.yaml").read_text()

SIZES = {  # size: target, MLL, trail balance (lock trigger), lock level, minis, micros  (12890029/12945790/12890136)
    25: (1250, 1000, 26100, 25100, 2, 20),
    50: (3000, 2000, 52100, 50100, 4, 40),
    100: (6000, 3000, 103100, 100100, 6, 60),
    150: (9000, 4500, 154600, 150100, 10, 100),
}
PRO_EVAL_DLL = {25: 600, 50: 1200, 100: 1800, 150: 2700}  # 12890029 / 12890122
PRO_FUNDED_DLL = {25: 600, 50: 1200, 100: 1800, 150: 2700}  # 12890069 (25K conflicts with 12890122 → VERIFY)
PRO_MIN_CYCLE = {25: 250, 50: 500, 100: 750, 150: 1000}  # 12890092
PRO_CAP = {25: (1000, 1500), 50: (2000, 2500), 100: (2500, 3000), 150: (3000, 3500)}  # 12890092
FLEX_DAY = {25: 100, 50: 150, 100: 200, 150: 250}  # 12945796
FLEX_CAP = {25: 1000, 50: 2000, 100: 2500, 150: 3000}  # 12945796
FLEX_SCALE = {  # 12945808: profit_from → micros
    25: [(0, 10), (1000, 20)],
    50: [(0, 20), (1000, 30), (2000, 40)],
    100: [(0, 30), (1000, 40), (2000, 50), (3000, 60)],
    150: [(0, 40), (1000, 50), (2000, 60), (3000, 80), (4500, 100)],
}


def block(text: str, key: str, new: str) -> str:
    """Replace a top-level YAML block (key: … up to the next top-level key)."""
    m = re.search(rf"^{key}:.*?(?=^\S)", text, flags=re.M | re.S)
    assert m, key
    return text[: m.start()] + new.rstrip() + "\n\n" + text[m.end() :]


def line(text: str, key: str, new: str) -> str:
    m = re.search(rf"^{key}:.*$", text, flags=re.M)
    assert m, key
    return text[: m.start()] + new + text[m.end() :]


def make(plan: str, k: int) -> str:
    tgt, mll, trail, lock, minis, micros = SIZES[k]
    size = k * 1000
    pro = plan == "pro"
    scale = size / 25000
    t = TPL.replace("mso: {enabled: true, ", "mso: {enabled: false, ")  # D91: MSO off in every offered plan
    t = re.sub(r"\A(#.*\n)+", "", t)
    name = "LucidPro" if pro else "LucidFlex"
    head = (
        f"# Paytience rule profile — Lucid Trading {name} {k}K\n"
        f"# From Lucid's help center 2026-11-05 (support.lucidtrading.com/en/articles/<id>; ids in comments).\n"
        f"# Generated by backend/scripts/make_plans.py. # VERIFY = not stated by Lucid or conflicting — confirm it.\n"
    )
    t = line(t, "account_size", f"account_size: {size}")
    t = line(
        t,
        "purchase",
        f"purchase: {{drawdown_type: eod, dll_enabled: true, consistency_pct: 40}}"
        + ("   # user 2026-11-13, lucidtrading.com plan card (Pro: 40%)" if pro else "   # Flex eval 40% (50% add-on) 12945805"),
    )
    t = line(
        t, "max_contracts", f"max_contracts: {{minis: {minis}, micros: {micros}}}                 # 12890029/12945790"
    )
    edll = PRO_EVAL_DLL[k] if pro else None
    dscale = (
        "\n  dll_scale_above_lock_pct: 60   # VERIFY interpretation: card says 'LucidScale DLL (above initial trail): 60% of "
        "peak EOD balance'; implemented as 60% of the peak EOD PROFIT (peak EOD balance - starting balance) once the MLL "
        "has locked (= above the initial trail)"
        if pro
        else ""
    )
    t = block(
        t,
        "eval",
        f"""eval:
  profit_target: {tgt}
  consistency_max_day_pct: 40{"            # user 2026-11-13, lucidtrading.com plan card" if pro else "            # 12945805"}
  min_profitable_days: {1 if pro else 3}{"                # kept; 40% consistency already forces >= 3 profitable days. The card also shows 'One Day Pass Eval' (25K/100K), which conflicts with a 40% eval consistency # VERIFY" if pro else "                # 12945790"}
  max_loss_limit: {mll}
  drawdown_type: eod                   # 12890136 / 12945815
  daily_loss_limit: {edll if edll is not None else "null"}{"                # VERIFY Flex DLL amount not stated (on/off at checkout)" if not pro else "               # 12890122 soft; 25K 600 = lucidtrading.com plan card 2026-11-13"}{dscale}
  lock_trigger: {trail}
  lock_level: {lock}
  news_allowed_by_firm: true           # 11404728
  news_breach_min_before: 1
  news_breach_min_after: 1""",
    )
    fdll = PRO_FUNDED_DLL[k] if pro else None
    if pro:
        payout = (
            f"  payout:   # 12890092, 16558826\n"
            f"    split: 0.90\n    buffer: {trail}\n    min_request: 500\n    min_cycle_profit: {PRO_MIN_CYCLE[k]}\n"
            f"    max_first: {PRO_CAP[k][0]}\n    max_next: {PRO_CAP[k][1]}\n    max_payouts: 5\n"
            f"    min_profitable_days: 3   # VERIFY interpretation of 'Days to Payout 3' (lucidtrading.com plan card, "
            f"user 2026-11-13): 3 profitable days (profit > 0) per payout cycle"
        )
        scaling = ""
        pcons = (
            '\n  payout_consistency: {pct: 40, legacy_pct: 35, legacy_cutoff: "2025-11-28T15:00:00-05:00"}'
            '   # D89 Lucid support "Consistency Percentage" 2026-08-26: FUNDED payout eligibility, not a breach; '
            "35% for accounts bought/reset on or before 11/28/2025 3 PM ET"
        )
    else:
        pcons = ""
        payout = (
            f"  payout: {{split: 0.90, buffer: {lock}, min_request: 500, min_cycle_profit: 1, max_first: {FLEX_CAP[k]}, "
            f"max_next: {FLEX_CAP[k]}, max_pct_of_profit: 0.5, min_profitable_days: 5, min_day_profit: {FLEX_DAY[k]}, "
            f"max_payouts: 5, lock_mll_on_payout: true}}   # 12945796, 12945815"
        )
        tiers = ", ".join(f"{{profit_from: {a}, micros: {b}}}" for a, b in FLEX_SCALE[k])
        scaling = f"\n  scaling: [{tiers}]   # 12945808 (updated at end of session)"
    t = block(
        t,
        "funded",
        f"""funded:
  max_loss_limit: {mll}
  drawdown_type: eod                   # 12890136 / 12945815
  lock_trigger: {trail}
  lock_level: {lock}
  daily_loss_limit: {fdll if fdll is not None else "null"}{"               # 12890069 fixed part (25K 600 per plan card 2026-11-13)" if pro else "                # VERIFY Flex funded DLL amount not stated"}{dscale}
  consistency_max_day_pct: {40 if pro else "null"}{"            # Pro funded 40% for payouts 12890109" if pro else "          # Flex funded: none 12945795"}
  news_allowed_by_firm: true           # 11404728
  news_breach_min_before: 1
  news_breach_min_after: 1
  max_daily_profit_live_trigger: null  # Pro/Flex: no $-per-day live trigger (review pool after payout 5, 16558826)
  payouts_to_live: 1                   # 16558826: each funded account needs ≥ 1 payout
  payouts_live_review: 5               # 16558826: review pool after payout 5{scaling}{pcons}
{payout}""",
    )
    t = line(
        t,
        "live",
        f"live: {{starting_balance: 0, max_loss_limit: {mll}, drawdown_type: eod, lock_trigger: {mll + 100}, "
        f"lock_level: 100, sim_payout_cap_on_move: 0}}   # 16558826 (lock at $100 once profit = start DD) VERIFY",
    )
    # account-size dependent internal tunables (the user's own limits, not Lucid rules)
    t = re.sub(
        r"^  cushion_target_balance: .*$", f"  cushion_target_balance: {lock + int(3000 * scale)}", t, flags=re.M
    )
    t = re.sub(
        r"^  consistency_day_stop_buffer_pct: .*$",
        "  consistency_day_stop_buffer_pct: 2   # D138 user 2026-11-13: day stop at 38 % (40 % consistency − 2)",
        t,
        flags=re.M,
    )
    t = re.sub(r"^  funded_consistency_reference_min: .*$", f"  funded_consistency_reference_min: {tgt}", t, flags=re.M)
    t = re.sub(r"^  internal_max_micros: .*$", f"  internal_max_micros: {min(micros, int(10 * scale))}", t, flags=re.M)
    t = re.sub(r"^  pause_below_risk_base: .*$", f"  pause_below_risk_base: {int(500 * scale)}", t, flags=re.M)
    t = re.sub(r"^  sweep_above: .*$", f"  sweep_above: {lock + int(3000 * scale)}", t, flags=re.M)
    dll = PRO_FUNDED_DLL[k] if pro else None
    cap = int((dll - 100) * 0.4) if dll else None  # two max losses + slippage must fit inside the DLL (§11 test)
    t = re.sub(r"^  max_risk_usd: .*$", f"  max_risk_usd: {cap if cap else 'null'}", t, count=1, flags=re.M)
    t = re.sub(
        r"^  consistency_on_funded: .*$", f"  consistency_on_funded: {'true' if pro else 'false'}", t, flags=re.M
    )
    return head + t


if __name__ == "__main__":
    for plan in ("pro", "flex"):
        for k in SIZES:
            (ROOT / f"lucid_{plan}_{k}k.yaml").write_text(make(plan, k))
            print("wrote", f"lucid_{plan}_{k}k.yaml")
